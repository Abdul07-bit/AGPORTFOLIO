// ─────────────────────────────────────────────────────────────────────────────
// Personal configuration — the single place for contact details and links.
//
// Anything left as `null` is hidden on the site (never shown as a dead link).
// See README.md → "Configuration checklist" before deploying.
// The profile links and resume can also be changed at runtime from /admin
// (see src/data/settings.ts); these values are the defaults.
// ─────────────────────────────────────────────────────────────────────────────

export interface SocialLink {
  id: string
  label: string
  href: string | null
}

export interface Profile {
  name: string
  initials: string
  role: string
  /** Public contact email. Required for the email action and the mailto form fallback. */
  email: string | null
  social: SocialLink[]
  /** Optional availability line in the hero. Keep null unless you will keep it accurate. */
  availability: string | null
  /** Place a real resume at public/resume.pdf — the download button appears automatically. */
  resume: { path: string; downloadName: string }
  location: string
  timeZone: string
  timeZoneLabel: string
  /** `base` is the original photo (structured data); `cutout` is the background-removed version shown on the site. */
  portrait: { base: string; cutout: string; widths: number[]; width: number; height: number; alt: string }
  bio: string
  education: {
    degree: string
    institution: string
    place: string
    graduation: string
    /** Confirm against the latest academic record before publishing; null hides it. */
    cgpa: string | null
  }
  certifications: { name: string; issuer?: string; date: string }[]
  focus: string[]
  languages: { name: string; level: string | null }[]
}

